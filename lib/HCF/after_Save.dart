  Color _getColor(String colorName) {
    switch (colorName.toLowerCase()) {
      case 'Y':
        return Colors.yellow;
      case 'R':
        return Colors.red;
      case 'B':
        return Colors.blue;
      case 'W':
        return Colors.white;
      default:
        return Colors.grey;
    }
  }

