  Future<void> GetWasteGeneratedByList() async {
    SharedPreferences prefs = await SharedPreferences.getInstance();
    var token = prefs.getString('Token');
    try {
      final response = await http.get(
        Uri.parse('$masterurl$WASTE_GENERATED_BY_LOOKUP'),
        headers: {
          'Content-Type': 'application/json; charset=UTF-8',
          'Accept': 'application/json ; charset=UTF-8',
          'Authorization': 'Bearer $token',
        },
      );
      if (response.statusCode == 200 || response.statusCode == 201) {
        final jsonResponse = jsonDecode(response.body);
        if (jsonResponse['status'] == 'success' && jsonResponse['data'] is List) {
          if (!mounted) return;
          setState(() {
            wasteGeneratedByLookup = {
              for (var item in jsonResponse['data'])
                item['lookupDetId']: WasteGeneratedBy.fromJson(item),
            };
          });
        }
      }
    } catch (e) {
      print('Error fetching waste generated by list: $e');
    }
  }

  Future<void> GetCategoryList() async {
    setState(() {
      isLoadingColor = true;
    });
    SharedPreferences prefs = await SharedPreferences.getInstance();
    var token = prefs.getString('Token');
    try {
      final headers = {
        'Content-Type': 'application/json; charset=UTF-8',
        'Accept': 'application/json ; charset=UTF-8',
        'Authorization': 'Bearer $token',
      };

      final url = Uri.parse('${baseurl}${CATEGORY_LOOKUP}');

      final response = await http.get(url, headers: headers);

      print(response.body);

      if (response.statusCode == 201) {
        final jsonResponse = jsonDecode(response.body);
        final List<dynamic> data = jsonResponse['data'];

        setState(() {
          wasteColorLookup = {
            for (var item in data) item['lookupDetId']: item['lookupDetDescEn'],
