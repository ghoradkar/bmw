          //     ),
          //   );
          // } else {
          // If single barcode image
          final Uint8List imageBytes = response.bodyBytes;
          Navigator.push(
            context,
            MaterialPageRoute(
              builder: (_) => BarcodeImageScreen(imageBytes: imageBytes),
            ),
          );
          //}
        } catch (_) {
          // Fallback to single image
